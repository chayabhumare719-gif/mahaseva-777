export function getLocalizedFormName(name: LocalizedString, lang: Language): string {
  if (lang === 'mr' || lang === 'en') return name[lang];
  if (name[lang]) return name[lang]!;
  // Localize the "Form #XXX" prefix in the user's selected script while keeping the clean English service title
  return name.en.replace(/^Form\s+#/, `${FORM_WORD_PREFIX[lang]} #`);
}
